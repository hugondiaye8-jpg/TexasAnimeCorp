/* LALO interview thumbnail: poster frame at 03:48.
   The poster is generated by seeking a separate muted video instance, so
   playing the actual interview always starts at 00:00. The static SVG is the
   fallback if the device/browser cannot seek before playback. */
(function () {
  const video = document.querySelector('.editions-interview .tac-video');
  if (!video || typeof HTMLCanvasElement === 'undefined') return;

  const probe = document.createElement('video');
  probe.preload = 'auto';
  probe.muted = true;
  probe.playsInline = true;
  probe.setAttribute('playsinline', '');
  let finished = false;

  function cleanup() {
    if (finished) return;
    finished = true;
    probe.removeAttribute('src');
    probe.load();
  }

  probe.addEventListener('loadedmetadata', () => {
    if (!Number.isFinite(probe.duration) || probe.duration <= 0) {
      cleanup();
      return;
    }
    // The desired logo frame appears at 03:48 (228 seconds).
    probe.currentTime = Math.min(228, Math.max(0, probe.duration - 0.15));
  }, { once: true });

  probe.addEventListener('seeked', () => {
    if (finished) return;
    requestAnimationFrame(() => {
      if (finished || !probe.videoWidth || !probe.videoHeight) return;
      try {
        const canvas = document.createElement('canvas');
        canvas.width = probe.videoWidth;
        canvas.height = probe.videoHeight;
        const context = canvas.getContext('2d');
        if (!context) return;
        context.drawImage(probe, 0, 0, canvas.width, canvas.height);
        if (video.paused && video.currentTime === 0) {
          video.poster = canvas.toDataURL('image/jpeg', 0.9);
        }
      } catch (_) {
        // Keep the white-background Fontenay thumbnail as fallback.
      } finally {
        cleanup();
      }
    });
  }, { once: true });

  probe.addEventListener('error', cleanup, { once: true });
  video.addEventListener('play', cleanup, { once: true });

  probe.src = video.getAttribute('src');
  probe.load();
})();
